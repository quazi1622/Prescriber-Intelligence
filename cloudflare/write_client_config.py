"""Write public-only licensing configuration for PyInstaller build.

Only intended for build machines. The Worker private key is never embedded.
"""
import base64
import binascii
import os
import pathlib
import sys

url = os.environ.get("PI_WORKER_URL", "").strip().rstrip("/")
key = os.environ.get("PI_PUBLIC_KEY_B64", "").strip()

if not url.startswith("https://"):
    sys.exit("PI_WORKER_URL is missing or must start with https://. Set the GitHub Actions repository secret.")

if not key:
    sys.exit("PI_PUBLIC_KEY_B64 is missing. Set the matching public Ed25519 key as a GitHub Actions repository secret.")

try:
    public_key = base64.b64decode(key, validate=True)
except (binascii.Error, ValueError):
    sys.exit("PI_PUBLIC_KEY_B64 must be valid Base64 (no quotes, labels, or spaces).")

if len(public_key) != 32:
    sys.exit("PI_PUBLIC_KEY_B64 must decode to exactly 32 bytes (raw Ed25519 public key).")

path = pathlib.Path(__file__).resolve().parents[1] / "app" / "license_settings.py"
path.write_text(
    '"""Public licensing settings, generated by Windows CI."""\n'
    + f"WORKER_URL = {url!r}\nPUBLIC_KEY_B64 = {key!r}\n",
    encoding="utf-8",
)
print("Public Worker URL and verification key embedded (no private signing key).")
