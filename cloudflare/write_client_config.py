"""Write public-only licensing configuration for PyInstaller build.
Only intended for build machines. The Worker private key is never embedded.
"""
import base64,os,pathlib,sys
url=os.environ.get("PI_WORKER_URL","").strip().rstrip("/")
key=os.environ.get("PI_PUBLIC_KEY_B64","").strip()
if not url.startswith("https://") or len(base64.b64decode(key,validate=True))!=32:
    sys.exit("PI_WORKER_URL (https) and PI_PUBLIC_KEY_B64 (32-byte Ed25519 key) required")
path=pathlib.Path(__file__).resolve().parents[1]/"app"/"license_settings.py"
path.write_text(
    '"""Public licensing settings, generated by Windows CI."""\n'
    +f"WORKER_URL = {url!r}\nPUBLIC_KEY_B64 = {key!r}\n",
    encoding="utf-8")
print("Public Worker URL and verification key embedded (no private signing key).")
